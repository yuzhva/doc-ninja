import { execSync } from 'child_process';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');
const isWin = process.platform === 'win32';

// Ensure output directory exists
const distDir = path.join(rootDir, 'dist', 'python-scripts');
if (!fs.existsSync(distDir)) {
  fs.mkdirSync(distDir, { recursive: true });
}

console.log('📦 Setting up temporary Python environment...');
const venvDir = path.join(rootDir, '.venv-build');

// Clean previous venv if exists
if (fs.existsSync(venvDir)) {
  fs.rmSync(venvDir, { recursive: true, force: true });
}

// Create venv
const pythonCmd = isWin ? 'python' : 'python3';
try {
  execSync(`${pythonCmd} -m venv .venv-build`, {
    cwd: rootDir,
    stdio: 'inherit',
  });
} catch (error) {
  console.error('Failed to create venv. Make sure python is installed.');
  process.exit(1);
}

// Determine paths to venv executables
const venvBin = isWin
  ? path.join(venvDir, 'Scripts')
  : path.join(venvDir, 'bin');
const pipCmd = path.join(venvBin, isWin ? 'pip.exe' : 'pip');
const pyInstallerCmd = path.join(
  venvBin,
  isWin ? 'pyinstaller.exe' : 'pyinstaller',
);

console.log('⬇️ Installing build dependencies...');
// Install dependencies inside venv
execSync(`"${pipCmd}" install pyinstaller openpyxl`, {
  cwd: rootDir,
  stdio: 'inherit',
});

console.log('🔨 Compiling Python scripts...');
const scripts = ['convert_xlsx_to_static', 'slice_xlsx_for_chunks'];

for (const script of scripts) {
  console.log(`Building ${script}...`);
  const scriptPath = path.join('src', 'python-scripts', `${script}.py`);
  // Run PyInstaller
  const cmd = `"${pyInstallerCmd}" --onefile --distpath "${distDir}" --name ${script} "${scriptPath}"`;
  execSync(cmd, { cwd: rootDir, stdio: 'inherit' });
}

console.log('🧹 Cleaning up build artifacts...');
// Remove venv
fs.rmSync(venvDir, { recursive: true, force: true });
// Remove build folder generated by PyInstaller
fs.rmSync(path.join(rootDir, 'build'), { recursive: true, force: true });

// Remove spec files
for (const script of scripts) {
  const specFile = path.join(rootDir, `${script}.spec`);
  if (fs.existsSync(specFile)) {
    fs.unlinkSync(specFile);
  }
}

console.log('✅ Python build complete.');
