// execFileSync rather than execSync: execSync always runs the command through
// a shell (cmd.exe on Windows). Starting the executables directly
// keeps the shell out of the chain. (pnpm itself also runs scripts via cmd.exe
// unless its `script-shell` is set to another shell.)
import { execFileSync } from 'child_process';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');
const isWin = process.platform === 'win32';
const isMac = process.platform === 'darwin';

// On macOS the binaries are built fat (x86_64 + arm64), so one universal
// Electron build (what the Mac App Store gets for Intel and Apple silicon)
// can run them on both. That needs a universal2 Python: the python.org
// installer is one, Homebrew's python3 is arm64-only. PYTHON=/path/to/python3
// overrides the interpreter.
const macUniversalPython =
  '/Library/Frameworks/Python.framework/Versions/Current/bin/python3';
const macUniversal =
  isMac && (!!process.env.PYTHON || fs.existsSync(macUniversalPython));
if (isMac && !macUniversal) {
  console.warn(
    `⚠️ No universal2 Python at ${macUniversalPython}: building for ${process.arch} only.\n` +
      '   A Mac App Store (universal) build refuses these binaries. Install Python from python.org or set PYTHON.',
  );
}

// Ensure output directory exists
const distDir = path.join(rootDir, 'dist', 'python-scripts');
if (!fs.existsSync(distDir)) {
  fs.mkdirSync(distDir, { recursive: true });
}

console.log('📦 Setting up temporary Python environment...');
const venvDir = path.join(rootDir, '.venv-build');

// Clean previous venv if exists
if (fs.existsSync(venvDir)) {
  fs.rmSync(venvDir, { recursive: true, force: true });
}

// Create venv
const pythonCmd =
  process.env.PYTHON ??
  (isWin ? 'python' : macUniversal ? macUniversalPython : 'python3');
try {
  execFileSync(pythonCmd, ['-m', 'venv', '.venv-build'], {
    cwd: rootDir,
    stdio: 'inherit',
  });
} catch (error) {
  console.error('Failed to create venv. Make sure python is installed.');
  process.exit(1);
}

// Determine paths to venv executables
const venvBin = isWin
  ? path.join(venvDir, 'Scripts')
  : path.join(venvDir, 'bin');
const pipCmd = path.join(venvBin, isWin ? 'pip.exe' : 'pip');
const pyInstallerCmd = path.join(
  venvBin,
  isWin ? 'pyinstaller.exe' : 'pyinstaller',
);

console.log('⬇️ Installing build dependencies...');
// Install dependencies inside venv
execFileSync(pipCmd, ['install', 'pyinstaller', 'openpyxl'], {
  cwd: rootDir,
  stdio: 'inherit',
});

console.log('🔨 Compiling Python scripts...');
const scripts = [
  'convert_xlsx_to_static',
  'slice_xlsx_for_chunks',
  'sanitize_xlsx',
];

for (const script of scripts) {
  console.log(`Building ${script}...`);
  const scriptPath = path.join('src', 'python-scripts', `${script}.py`);
  // Run PyInstaller
  execFileSync(
    pyInstallerCmd,
    [
      '--onefile',
      ...(macUniversal ? ['--target-arch', 'universal2'] : []),
      '--distpath',
      distDir,
      '--name',
      script,
      scriptPath,
    ],
    { cwd: rootDir, stdio: 'inherit' },
  );
}

console.log('🧹 Cleaning up build artifacts...');
// Remove venv
fs.rmSync(venvDir, { recursive: true, force: true });
// Remove build folder generated by PyInstaller
fs.rmSync(path.join(rootDir, 'build'), { recursive: true, force: true });

// Remove spec files
for (const script of scripts) {
  const specFile = path.join(rootDir, `${script}.spec`);
  if (fs.existsSync(specFile)) {
    fs.unlinkSync(specFile);
  }
}

console.log('✅ Python build complete.');
